#!/usr/bin/env python3
"""The mesh radio's presets: MeshCore's community-suggested radio settings
made into the engine's table.

    python tools/mesh/meshpresets.py [--fetch] [--json FILE] [-o FILE]

The presets are those MeshCore's own apps offer, published at
https://api.meshcore.nz/api/v1/config ("suggested_radio_settings").  A copy
of that list is kept in tools/mesh/meshcore-presets.json, so the table can be
made again without the network; --fetch refreshes the copy from the URL
first (and says when it was fetched).

Output (default src/hal/host/HostMeshPresets.inc): the C table that
hal/host/HostMesh.cpp includes - one {name, frequency (MHz), bandwidth (kHz),
spreading factor, coding rate (5-8: 4/5-4/8), path hash size (bytes, 1-3)}
per preset, in the list's order.  A preset without network_settings gets a
path hash size of 1, MeshCore's own default.

Regenerate after a --fetch; never edit the .inc by hand.
"""

import argparse
import datetime
import json
import os
import sys
import urllib.request

URL = "https://api.meshcore.nz/api/v1/config"
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
DEFAULT_JSON = os.path.join(HERE, "meshcore-presets.json")
DEFAULT_OUT = os.path.join(ROOT, "src", "hal", "host", "HostMeshPresets.inc")


def fetch(path):
    # (the server turns away urllib's own User-Agent)
    request = urllib.request.Request(URL, headers={"User-Agent": "newton-re meshpresets.py"})
    with urllib.request.urlopen(request, timeout=30) as response:
        config = json.load(response)
    kept = {
        "source": URL,
        "fetched": datetime.date.today().isoformat(),
        "suggested_radio_settings": config["config"]["suggested_radio_settings"],
    }
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(kept, f, indent=1, ensure_ascii=False)
        f.write("\n")


def c_string(text):
    # (the names are UTF-8 in the engine, as everything crossing it is)
    out = []
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if ch in '"\\':
            out.append("\\" + ch)
        elif 32 <= byte < 127:
            out.append(ch)
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def make_table(kept):
    entries = kept["suggested_radio_settings"]["entries"]
    lines = [
        "// MeshCore's community-suggested radio presets, from",
        "// %s (fetched %s)." % (kept["source"], kept["fetched"]),
        "// Generated by tools/mesh/meshpresets.py from tools/mesh/meshcore-presets.json:",
        "// regenerate, don't edit.",
        "//",
        "// {name, frequency MHz, bandwidth kHz, spreading factor, coding rate (4/n), path hash size}",
        "",
    ]
    for e in entries:
        hash_size = int((e.get("network_settings") or {}).get("path_hash_size", 1))
        lines.append("\t{ %s, %sf, %sf, %d, %d, %d }," % (
            c_string(e["title"]), float(e["frequency"]), float(e["bandwidth"]),
            int(e["spreading_factor"]), int(e["coding_rate"]), hash_size))
    return "\n".join(lines) + "\n"


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--fetch", action="store_true", help="refresh the kept list from " + URL + " first")
    parser.add_argument("--json", default=DEFAULT_JSON, help="the kept list (default: %(default)s)")
    parser.add_argument("-o", "--output", default=DEFAULT_OUT, help="the table (default: %(default)s)")
    args = parser.parse_args(argv)
    if args.fetch:
        fetch(args.json)
    with open(args.json, encoding="utf-8") as f:
        kept = json.load(f)
    table = make_table(kept)
    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write(table)
    print("%s: %d presets" % (args.output, len(kept["suggested_radio_settings"]["entries"])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
